class Bus {

	String busNumber;
	String route;
	String busType;
	boolean isRunning;

	public void busInfo() {
		System.out.println("BUS INFO PRINTING");
		System.out.println("BUS NUMBER : " + busNumber);
		System.out.println("ROUTE      : " + route);
		System.out.println("BUS TYPE   : " + busType);
		System.out.println("IS RUNNING : " + isRunning);
	}

}