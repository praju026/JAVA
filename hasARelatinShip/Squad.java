class Squad {

	String codeName;
	int soldierCount;
	String operationZone;
	boolean isActive;

	public void squadInfo() {
		System.out.println("SQUAD INFO PRINTING");
		System.out.println("CODE NAME       : " + codeName);
		System.out.println("SOLDIER COUNT   : " + soldierCount);
		System.out.println("OPERATION ZONE  : " + operationZone);
		System.out.println("IS ACTIVE       : " + isActive);
	}
}
