package com.xworkz.flipkart.category;

public class FlipkartCategory {
    String dailyUtilities;
    String sports;
    String shoes;
    String dress;
    String food;
    public void setDailyUtilities(String dailyUtilities) {
        this.dailyUtilities = dailyUtilities;
    }

    public String getDailyUtilities() {
        return dailyUtilities;
    }

    public void setSports(String sports) {
        this.sports = sports;
    }

    public String getSports() {
        return sports;
    }

    public void setShoes(String shoes) {
        this.shoes = shoes;
    }

    public String getShoes() {
        return shoes;
    }

    public void setDress(String dress) {
        this.dress = dress;
    }

    public String getDress() {
        return dress;
    }

    public void setFood(String food) {
        this.food = food;
    }

    public String getFood() {
        return food;
    }
}
